using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

/// <summary>
/// C# 注释合规性检查器主编排器，基于 Roslyn 语法树和语义模型分析。
/// 负责文件加载、语义模型创建、语法树遍历调度，并将具体检查委托给 DocCommentCheckers、
/// InlineCommentCheckers 和 CommentSyntaxWalker。
/// </summary>
public class CommentChecker
{
    private readonly CommentRules _rules;

    private static readonly string[] DefaultPreprocessorSymbols = { "UNITY_EDITOR", "UNITY_2022", "UNITY_6000" };
    private static List<MetadataReference>? _cachedReferences;
    private SemanticModel? _semanticModel;
    private bool _useSemanticAnalysis;

    /// <summary>
    /// 成员类型到 doc_missing_* 规则名称的映射表。
    /// </summary>
    private static readonly Dictionary<string, string> MemberTypeToRule = new()
    {
        [MemberTypes.Class] = RuleNames.DocMissingClass,
        [MemberTypes.Interface] = RuleNames.DocMissingInterface,
        [MemberTypes.Struct] = RuleNames.DocMissingStruct,
        [MemberTypes.Enum] = RuleNames.DocMissingEnum,
        [MemberTypes.EnumValue] = RuleNames.DocMissingEnumValue,
        [MemberTypes.Delegate] = RuleNames.DocMissingDelegate,
        [MemberTypes.Event] = RuleNames.DocMissingEvent,
        [MemberTypes.Method] = RuleNames.DocMissingMethod,
        [MemberTypes.Property] = RuleNames.DocMissingProperty,
        [MemberTypes.Field] = RuleNames.DocMissingField,
        [MemberTypes.Constructor] = RuleNames.DocMissingConstructor,
        [MemberTypes.Operator] = RuleNames.DocMissingOperator,
    };

    /// <summary>
    /// 使用指定规则配置初始化注释检查器。
    /// </summary>
    /// <param name="rules">注释检查规则配置。</param>
    public CommentChecker(CommentRules rules)
    {
        _rules = rules;
    }

    /// <summary>
    /// 根据成员类型获取对应的 doc_missing_* 规则名称。
    /// </summary>
    /// <param name="memberType">成员类型（如 class、method 等）。</param>
    /// <returns>规则名称。</returns>
    internal static string GetDocMissingRuleName(string memberType)
    {
        return MemberTypeToRule.TryGetValue(memberType, out var ruleName) ? ruleName : RuleNames.DocMissingClass;
    }

    /// <summary>
    /// 检测文件是否为自动生成代码，根据文件头（前 5 行）是否包含 &lt;auto-generated /&gt; 标记判断。
    /// 匹配规则与门禁脚本 collect_review_targets.py 的 is_auto_generated_header 保持一致：
    /// 标记可出现在行内任意位置，兼容 &lt;auto-generated 与 &lt;auto generated（空格版）两种写法，且大小写不敏感。
    /// </summary>
    /// <param name="filePath">文件完整路径。</param>
    /// <returns>是否为自动生成代码。</returns>
    public static bool IsAutoGenerated(string filePath)
    {
        try
        {
            var lines = File.ReadLines(filePath).Take(5);
            return lines.Any(l =>
                l.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
                || l.IndexOf("<auto generated", StringComparison.OrdinalIgnoreCase) >= 0);
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// 获取语义模型（用于外部查询，如 CommentSyntaxWalker）。
    /// </summary>
    internal SemanticModel? GetSemanticModel() => _semanticModel;

    /// <summary>
    /// 检查单个 .cs 文件的注释合规性。
    /// 解析源文件、创建语义模型、遍历语法树并收集所有注释问题。
    /// </summary>
    /// <param name="filePath">.cs 文件路径。</param>
    /// <returns>注释问题列表。</returns>
    public List<CommentIssue> CheckFile(string filePath)
    {
        var results = new List<CommentIssue>();
        var sourceCode = File.ReadAllText(filePath);

        var parseOptions = CSharpParseOptions.Default
            .WithPreprocessorSymbols(DefaultPreprocessorSymbols);
        var tree = CSharpSyntaxTree.ParseText(sourceCode, parseOptions);

        // 检查 Roslyn 语法解析错误，作为 parse_error 上报
        if (_rules.IsEnabled(RuleNames.ParseError))
        {
            var parseDiagnostics = tree.GetDiagnostics()
                .Where(d => d.Severity == DiagnosticSeverity.Error)
                .ToList();
            foreach (var diagnostic in parseDiagnostics)
            {
                var errLine = diagnostic.Location.GetLineSpan().StartLinePosition.Line + 1;
                results.Add(new CommentIssue
                {
                    File = filePath,
                    Line = errLine,
                    Severity = _rules.GetIssueSeverity(RuleNames.ParseError, IssueCategories.ParseError),
                    Category = IssueCategories.ParseError,
                    RuleName = RuleNames.ParseError,
                    Member = "",
                    MemberType = "",
                    Message = $"文件解析错误: {diagnostic.GetMessage()}",
                    CodeSnippet = ""
                });
            }
        }

        _useSemanticAnalysis = TryCreateSemanticModel(tree, filePath);

        var root = tree.GetCompilationUnitRoot();

        DocCommentCheckers.CheckFileHeader(root, filePath, results, _rules);

        var walker = new CommentSyntaxWalker(this, results, filePath, sourceCode, _rules);
        walker.Visit(root);

        return results;
    }

    /// <summary>
    /// 尝试创建 Roslyn 语义模型，用于启用语义级别的一致性检查。
    /// 若无法加载程序集引用或创建失败，则回退到纯语法分析模式。
    /// </summary>
    /// <param name="tree">语法树。</param>
    /// <param name="filePath">文件路径（用于查找 Unity 项目引用）。</param>
    /// <returns>语义模型是否创建成功。</returns>
    private bool TryCreateSemanticModel(SyntaxTree tree, string filePath)
    {
        try
        {
            var references = GetAssemblyReferences(filePath);
            if (references.Count == 0)
            {
                Console.Error.WriteLine("语义分析: 未找到可用的程序集引用，回退到语法分析模式。");
                return false;
            }

            var compilation = CSharpCompilation.Create(
                "CommentChecker",
                new[] { tree },
                references,
                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
                    .WithAllowUnsafe(true));

            _semanticModel = compilation.GetSemanticModel(tree);
            return true;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"语义分析: 创建语义模型失败 - {ex.Message}，回退到语法分析模式。");
            return false;
        }
    }

    /// <summary>
    /// 获取分析文件所需的程序集引用集合，优先从 Unity 项目的 Library/ScriptAssemblies 目录加载。
    /// 使用缓存避免重复加载。
    /// </summary>
    /// <param name="filePath">被分析文件的路径。</param>
    /// <returns>程序集引用列表。</returns>
    private static List<MetadataReference> GetAssemblyReferences(string filePath)
    {
        if (_cachedReferences != null) return _cachedReferences;

        var references = new List<MetadataReference>();

        var scriptAssembliesDir = FindScriptAssembliesDir(filePath);
        if (scriptAssembliesDir != null && Directory.Exists(scriptAssembliesDir))
        {
            foreach (var dll in Directory.GetFiles(scriptAssembliesDir, "*.dll"))
            {
                try { references.Add(MetadataReference.CreateFromFile(dll)); }
                catch { }
            }
        }

        var runtimeDir = Path.GetDirectoryName(typeof(object).Assembly.Location);
        if (runtimeDir != null)
        {
            foreach (var lib in new[] { "System.Runtime.dll", "System.Collections.dll", "System.Linq.dll" })
            {
                var path = Path.Combine(runtimeDir, lib);
                if (File.Exists(path))
                {
                    try { references.Add(MetadataReference.CreateFromFile(path)); }
                    catch { }
                }
            }
        }

        _cachedReferences = references;
        return references;
    }

    /// <summary>
    /// 向上查找 Unity 项目的 Library/ScriptAssemblies 目录，用于加载项目程序集引用。
    /// 从文件所在目录向上遍历，直到找到包含 .git 或 CODEBUDDY.md 的根目录。
    /// </summary>
    /// <param name="filePath">文件路径。</param>
    /// <returns>Library/ScriptAssemblies 目录路径，若未找到则返回 null。</returns>
    private static string? FindScriptAssembliesDir(string filePath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(filePath));
        while (dir != null)
        {
            var candidate = Path.Combine(dir, "Library", "ScriptAssemblies");
            if (Directory.Exists(candidate)) return candidate;

            if (Directory.Exists(Path.Combine(dir, ".git")) ||
                File.Exists(Path.Combine(dir, "CODEBUDDY.md")))
            {
                var rootCandidate = Path.Combine(dir, "Library", "ScriptAssemblies");
                if (Directory.Exists(rootCandidate)) return rootCandidate;
                break;
            }

            var parent = Path.GetDirectoryName(dir);
            if (parent == dir) break;
            dir = parent;
        }
        return null;
    }
}
