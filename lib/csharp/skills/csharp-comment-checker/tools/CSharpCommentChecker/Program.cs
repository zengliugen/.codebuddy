using System.Text.Json;
using System.Text.Json.Serialization;

/// <summary>
/// C# 注释合规性检查工具，使用 Roslyn 解析 .cs 文件并检查注释是否满足项目规范。
/// </summary>
public static class Program
{
    /// <summary>
    /// 程序入口点。
    /// </summary>
    /// <param name="args">
    /// 命令行参数：
    ///   第一个参数 — 目标文件路径或目录路径。
    ///   可选 --config &lt;路径&gt; — 指定规则配置文件。
    ///   可选 --exclude-generated — 排除 Generated/ 和 Gen/ 目录。
    ///   可选 --json — 以 JSON 格式输出。
    /// </param>
    public static void Main(string[] args)
    {
        var targetPaths = GetTargetPaths(args);
        if (targetPaths.Count == 0)
        {
            Console.Error.WriteLine("用法: CSharpCommentChecker <文件路径或目录路径...> [--config <配置路径>] [--exclude-generated] [--json]");
            Environment.Exit(1);
        }

        var configPath = GetArgValue(args, "--config");
        var excludeGenerated = args.Contains("--exclude-generated");
        var jsonOutput = args.Contains("--json");

        // 加载规则配置：配置分层（引擎侧通用 + 项目侧），深度合并后使用，项目侧值覆盖引擎侧。
        // 配置缺失/损坏即报错退出，不使用内置默认配置。
        CommentRules rules;
        try
        {
            var configFile = ConfigResolver.Resolve(configPath);
            rules = CommentRules.Load(configFile);
        }
        catch (CommentRulesConfigException ex)
        {
            Console.Error.WriteLine($"错误: {ex.Message}");
            Environment.Exit(3);
            return;
        }

        // 收集所有 .cs 文件（使用配置文件中的排除规则）
        var csFiles = GetCsFiles(targetPaths, rules, excludeGenerated);

        var allResults = new List<CommentIssue>();
        var skipAutoGenerated = rules.IsAutoGeneratedEnabled();
        foreach (var file in csFiles)
        {
            try
            {
                // 检查文件头是否包含 /// <auto-generated /> 标记，若启用且存在则跳过
                if (skipAutoGenerated && CommentChecker.IsAutoGenerated(file))
                {
                    continue;
                }
                var checker = new CommentChecker(rules);
                var results = checker.CheckFile(file);
                allResults.AddRange(results);
            }
            catch (Exception ex)
            {
                allResults.Add(new CommentIssue
                {
                    File = file,
                    Line = 0,
                    Severity = rules.GetIssueSeverity(RuleNames.ParseError, IssueCategories.ParseError),
                    Category = IssueCategories.ParseError,
                    RuleName = RuleNames.ParseError,
                    Member = "",
                    MemberType = "",
                    Message = $"解析文件失败: {ex.Message}",
                    CodeSnippet = $"文件: {Path.GetFileName(file)}"
                });
            }
        }

        if (jsonOutput)
        {
            var options = new JsonSerializerOptions
            {
                WriteIndented = true,
                DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
                Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping
            };
            Console.WriteLine(JsonSerializer.Serialize(allResults, options));
        }
        else
        {
            PrintResults(allResults);
        }
    }

    /// <summary>
    /// 收集目标路径下的所有 .cs 文件，根据配置排除指定路径。
    /// </summary>
    private static List<string> GetCsFiles(List<string> paths, CommentRules rules, bool excludeGenerated)
    {
        var files = new List<string>();

        foreach (var path in paths)
        {
            if (File.Exists(path))
            {
                if (path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
                {
                    var fullPath = Path.GetFullPath(path).Replace('\\', '/');
                    if (!rules.IsExcluded(fullPath))
                    {
                        files.Add(fullPath);
                    }
                }
            }
            else if (Directory.Exists(path))
            {
                var allFiles = Directory.GetFiles(path, "*.cs", SearchOption.AllDirectories);
                foreach (var file in allFiles)
                {
                    var fullPath = Path.GetFullPath(file).Replace('\\', '/');
                    if (rules.IsExcluded(fullPath))
                    {
                        continue;
                    }
                    // 与排除路径匹配保持一致，按大小写不敏感判断生成代码目录
                    if (excludeGenerated
                        && (fullPath.IndexOf("/Generated/", StringComparison.OrdinalIgnoreCase) >= 0
                            || fullPath.IndexOf("/Gen/", StringComparison.OrdinalIgnoreCase) >= 0))
                    {
                        continue;
                    }
                    files.Add(fullPath);
                }
            }
            else
            {
                Console.Error.WriteLine($"路径不存在: {path}");
                Environment.Exit(1);
            }
        }

        return files;
    }

    /// <summary>
    /// 从命令行参数中获取命名参数的值。
    /// </summary>
    private static string? GetArgValue(string[] args, string argName)
    {
        var idx = Array.IndexOf(args, argName);
        if (idx >= 0 && idx + 1 < args.Length)
        {
            return args[idx + 1];
        }
        return null;
    }

    /// <summary>
    /// 从命令行参数中提取所有目标路径（非选项参数）。
    /// 已知选项 --config、--exclude-generated、--json 及其值不会被视为目标路径。
    /// </summary>
    private static List<string> GetTargetPaths(string[] args)
    {
        var paths = new List<string>();
        var skipNext = false;
        foreach (var arg in args)
        {
            if (skipNext)
            {
                skipNext = false;
                continue;
            }
            if (arg == "--config")
            {
                skipNext = true;
                continue;
            }
            if (arg == "--exclude-generated" || arg == "--json")
            {
                continue;
            }
            if (!arg.StartsWith("--"))
            {
                paths.Add(arg);
            }
        }
        return paths;
    }

    /// <summary>
    /// 格式化打印检查结果。
    /// </summary>
    private static void PrintResults(List<CommentIssue> results)
    {
        if (results.Count == 0)
        {
            Console.WriteLine("所有文件注释检查通过。");
            return;
        }

        var errors = results.Count(r => r.Severity == "error");
        var warnings = results.Count(r => r.Severity == "warning");
        var infos = results.Count(r => r.Severity == "info");

        Console.WriteLine($"检查完成: {results.Count} 个问题 ({errors} 错误, {warnings} 警告, {infos} 提示)");
        Console.WriteLine(new string('-', 80));

        var groupedByFile = results.GroupBy(r => r.File);
        foreach (var group in groupedByFile)
        {
            Console.WriteLine($"\n文件: {group.Key}");
            foreach (var issue in group.OrderBy(i => i.Line))
            {
                var severityTag = issue.Severity switch
                {
                    "error" => "[错误]",
                    "warning" => "[警告]",
                    "info" => "[提示]",
                    _ => "[未知]"
                };
                Console.WriteLine($"  行 {issue.Line}: {severityTag} [{issue.Category}] {issue.Message}");
                if (!string.IsNullOrEmpty(issue.Member))
                {
                    Console.WriteLine($"    成员: {issue.MemberType} {issue.Member}");
                }
            }
        }

        Console.WriteLine(new string('-', 80));
        Console.WriteLine($"合计: {results.Count} 个问题");
    }
}
