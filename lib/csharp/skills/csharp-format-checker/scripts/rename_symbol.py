# -*- coding: utf-8 -*-
"""C# 符号批量重命名入口脚本（按项目根 .editorconfig 的命名规则）。

职责：
1. 定位同目录下的 rename_symbol C# 工具工程（基于 Roslyn Renamer，与 Visual Studio 重命名同一引擎）。
2. 首次运行或源码更新时自动执行 dotnet build（产物落 bin/obj，由引擎根 .gitignore 兜底）。
3. 透传参数运行工具：默认 dry-run 只输出待改名清单，加 --apply 才落盘修改源码。
4. 以工具退出码作为本脚本退出码（0 成功 / 1 执行错误 / 2 参数错误 / 3 配置缺失）。

设计约束：
- 命名规则全部从项目根 .editorconfig 的 dotnet_naming_* 读取，脚本与工具内不内置任何项目前缀约定。
- 生成代码（<auto-generated>）、单字符名称、override 与显式接口实现不参与改名。
- 只分析传入的工程；其引用闭包中的工程仅作为引用方被同步改写，其他工程的引用需自行纳入。
"""

import argparse
import json
import os
import subprocess
import sys

# 工具工程与源文件（任一更新都需要重新构建）
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
TOOL_DIR = os.path.join(SCRIPT_DIR, "rename_symbol")
PROJECT_FILE = os.path.join(TOOL_DIR, "RenameSymbolTool.csproj")
OUTPUT_DLL = os.path.join(TOOL_DIR, "bin", "Debug", "net8.0", "RenameSymbolTool.dll")
SOURCE_FILES = (
    PROJECT_FILE,
    os.path.join(TOOL_DIR, "Program.cs"),
    os.path.join(TOOL_DIR, "EditorConfigNaming.cs"),
)


def ensure_built(no_build):
    """确保工具已构建且为最新；返回 True 表示可用。"""
    if not os.path.isfile(PROJECT_FILE):
        print("[错误] 未找到工具工程：%s" % PROJECT_FILE, file=sys.stderr)
        return False

    if no_build and os.path.isfile(OUTPUT_DLL):
        return True

    need_build = not os.path.isfile(OUTPUT_DLL)
    if not need_build:
        dll_mtime = os.path.getmtime(OUTPUT_DLL)
        for source in SOURCE_FILES:
            if os.path.isfile(source) and os.path.getmtime(source) > dll_mtime:
                need_build = True
                break

    if not need_build:
        return True

    print("[信息] 构建重命名工具……")
    command = ["dotnet", "build", PROJECT_FILE, "-c", "Debug", "-v", "q", "--nologo"]
    result = subprocess.run(command)
    if result.returncode != 0:
        print("[错误] 工具构建失败（退出码 %d）" % result.returncode, file=sys.stderr)
        return False

    return os.path.isfile(OUTPUT_DLL)


def find_project_root(start):
    """自 start 向上查找含 .editorconfig 的目录作为项目根；找不到返回 None。"""
    current = os.path.abspath(start)
    while True:
        if os.path.isfile(os.path.join(current, ".editorconfig")):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def load_exclude_dirs(project_root):
    """经索引 format_checker.config 读取忽略目录；索引或配置缺失时返回空列表（不阻断改名）。"""
    if not project_root:
        return []

    index_path = os.path.join(project_root, ".codebuddy", "project.index.json")
    if not os.path.isfile(index_path):
        return []

    try:
        with open(index_path, "r", encoding="utf-8") as handle:
            index = json.load(handle)
        entry = index.get("files", {}).get("format_checker.config", {})
        config_relative = entry.get("path", "")
        if not config_relative:
            return []
        config_path = os.path.join(project_root, config_relative)
        with open(config_path, "r", encoding="utf-8") as handle:
            config = json.load(handle)
        return [item for item in config.get("exclude_dirs", []) if isinstance(item, str) and item]
    except (OSError, ValueError):
        return []


def main():
    """解析参数、确保工具可用并透传运行。"""
    parser = argparse.ArgumentParser(
        description="按项目根 .editorconfig 的命名规则批量重命名 C# 符号（默认只试运行）",
        epilog="示例：python scripts/rename_symbol.py --dry-run <csproj 路径>",
    )
    parser.add_argument("projects", nargs="+", help="目标 csproj 路径（一个或多个）")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="落盘执行改名（默认 dry-run 只列清单）")
    mode.add_argument("--dry-run", action="store_true", help="试运行，只输出待改名清单（默认行为）")
    parser.add_argument("--editorconfig", default=None, help="显式指定 .editorconfig 路径（默认自 csproj 向上查找）")
    parser.add_argument("--no-build", action="store_true", help="跳过自动构建（工具已构建时使用）")
    args = parser.parse_args()

    if not ensure_built(args.no_build):
        return 1

    command = ["dotnet", OUTPUT_DLL, "--apply" if args.apply else "--dry-run"]
    if args.editorconfig:
        command.extend(["--editorconfig", args.editorconfig])

    # 忽略目录来自项目侧配置（与 dotnet format 的检查范围保持一致）
    project_root = find_project_root(args.projects[0])
    for exclude_dir in load_exclude_dirs(project_root):
        command.extend(["--exclude", exclude_dir])

    command.extend(args.projects)

    result = subprocess.run(command)
    return result.returncode


if __name__ == "__main__":
    sys.exit(main())
