def namespace_mappings():
    """取 UPM 包名前缀 → C# 根命名空间的映射列表。"""
    value = get("namespaceMapping.mappings")
    if not isinstance(value, list):
        raise ConfigError(
            "配置项 `namespaceMapping.mappings` 必须是数组%s" % (_MISSING_KEY_HINT % CONFIG_PATH)
        )
    return list(value)


def package_to_namespace(package_name):
    """由 UPM 包名推导 C# 根命名空间；无匹配映射时返回 None。

    `com.example.my-tool` 形式无匹配映射时返回 None（不猜测命名空间）。
    """
    for item in namespace_mappings():
        prefix = (item or {}).get("package_prefix") or ""
        namespace = (item or {}).get("namespace") or ""
        if prefix and namespace and package_name.startswith(prefix):
            suffix = package_name[len(prefix):]
            parts = [p for p in suffix.split(".") if p]
            return ".".join([namespace] + [p[:1].upper() + p[1:] for p in parts])
    return None


