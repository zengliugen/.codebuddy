#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
csharp-test-coverage 配置读取模块。

**设计原则（配置为唯一事实来源）**：配置分为两层，读取时**深度合并**（项目侧覆盖引擎侧）：

    tools/CSharpTestCoverage/coverage_config.json          # 引擎侧通用配置（随引擎入库共享）
    <项目根>/.codebuddy.project/.../coverage_config.project.json  # 项目侧配置（经索引定位）

引擎侧承载与项目无关的算法参数、映射策略与严重程度；项目侧承载运行时源码根、排除路径、
扫描范围、包名→命名空间映射、真实采集程序集前缀等项目相关内容。两层路径均由
`.codebuddy/project.index.json`（索引注册表）声明，脚本内**不硬编码**任何默认值、
项目专属路径、程序集名或包名。**配置缺失、损坏或缺少必需键时直接报错退出**，
不再回退内置默认值——避免「配置写了但没生效」的静默偏差。

本模块被 `check_coverage.py` / `collect_real_coverage.py` / `parse_unity_coverage.py` /
`generate_skeletons.py` 共用，避免各脚本重复实现配置读取逻辑。

配置字段说明（详见 references/config-guide.md）：

    exclude.paths                  排除路径片段（运行时侧不计入分母）
    exclude.autoGenerated          是否跳过文件头 auto-generated 标记文件
    runtimeRoots                   运行时源码根（相对项目根的前缀）
    scanScopes                     未指定目标时 --scope 取值 → 扫描根目录列表
    namespaceMapping.mappings      UPM 包名前缀 → C# 根命名空间（骨架命名空间推导）
    testRootMarkers                测试目录标识
    matching                       目录镜像与测试根命名
    realCoverage.*                 真实采集产物路径、程序集前缀/后缀、框架包标识
    skeleton.*                     骨架生成门槛与提示文案
"""

import json
import os
import sys


class ConfigError(RuntimeError):
    """配置缺失、损坏或缺少必需键时抛出；由 CLI 入口转为明确的错误退出。"""


def _skill_dirs():
    """由本模块位置推导技能目录与项目根（供未显式传参时使用）。"""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    skill_dir = os.path.dirname(script_dir)
    project_root = _find_project_root(script_dir)
    return skill_dir, project_root


def _find_project_root(start):
    """自 start 向上查找含 `.codebuddy` 或 `.git` 的目录作为项目根。

    使用锚点标志而非固定向上层数：目录结构调整后固定层数会定位到错误目录。
    找不到锚点时回退为「技能目录的上三级」，保持与原行为兼容。
    """
    current = os.path.abspath(start)
    while True:
        if os.path.isdir(os.path.join(current, ".codebuddy")) or os.path.isdir(os.path.join(current, ".git")):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
    return os.path.abspath(os.path.join(start, "..", "..", ".."))


def _find_codebuddy_dir(start):
    """自 start 向上查找名为 `.codebuddy` 的目录；找不到返回 None。"""
    current = os.path.abspath(start)
    while True:
        if os.path.basename(current) == ".codebuddy":
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def _resolve_project_config(codename, project_root):
    """经索引注册表解析项目侧配置路径（相对路径基准为项目根）。

    索引为跨项目共享的入库文件，只读 `files[codename].path`；路径必须是相对路径
    （拒绝绝对路径，防索引污染）。索引或项目侧配置缺失时报错退出，不兜底。
    """
    codebuddy_dir = _find_codebuddy_dir(os.path.dirname(os.path.abspath(__file__)))
    if not codebuddy_dir:
        raise ConfigError("未能定位 .codebuddy 目录（应位于项目根下）")
    index_path = os.path.join(codebuddy_dir, "project.index.json")
    if not os.path.isfile(index_path):
        raise ConfigError(
            "未找到项目配置索引：%s\n"
            "       该索引由 .codebuddy 引擎提供；若缺失，请确认引擎包完整。" % index_path
        )
    try:
        with open(index_path, "r", encoding="utf-8") as handle:
            index = json.load(handle)
    except (OSError, ValueError) as error:
        raise ConfigError("项目配置索引读取失败（%s）：%s" % (error, index_path))
    entry = (index.get("files") or {}).get(codename)
    if not isinstance(entry, dict) or not entry.get("path"):
        raise ConfigError("索引缺少配置项 `files.%s.path`：%s" % (codename, index_path))
    rel = entry["path"]
    if os.path.isabs(rel):
        raise ConfigError("索引 `files.%s.path` 必须为相对路径（当前为绝对路径）：%s" % (codename, rel))
    return os.path.normpath(os.path.join(project_root, rel))


def _deep_merge(base, override):
    """深度合并两份配置；项目侧（override）覆盖引擎侧（base）。

    - 字典：递归合并，逐键覆盖；
    - 列表：取并集（保持 base 顺序在前，去重）；
    - 标量：项目侧值覆盖引擎侧值。
    """
    if isinstance(base, dict) and isinstance(override, dict):
        merged = dict(base)
        for key, value in override.items():
            if key in merged:
                merged[key] = _deep_merge(merged[key], value)
            else:
                merged[key] = value
        return merged
    if isinstance(base, list) and isinstance(override, list):
        result = list(base)
        for item in override:
            if item not in result:
                result.append(item)
        return result
    return override


SKILL_DIR, PROJECT_ROOT = _skill_dirs()
ENGINE_CONFIG_PATH = os.path.join(SKILL_DIR, "tools", "CSharpTestCoverage", "coverage_config.json")
PROJECT_CONFIG_PATH = _resolve_project_config("coverage.project_config", PROJECT_ROOT)
# 合并结果落盘路径：供 C# 工具经 --config 读取（两侧合并后，工具侧无需感知分层）
CONFIG_PATH = os.path.join(SKILL_DIR, "tools", "CSharpTestCoverage", "coverage_config.merged.json")

_cached_config = None

# 缺少必需键时的统一提示：指明「配置是唯一来源」，并给出配置指南位置
_MISSING_KEY_HINT = "（配置为覆盖率数据的唯一来源，请补齐 %s；字段说明见该技能 references/config-guide.md）"


def _read_json(path, label):
    """读取 JSON 配置文件；缺失或损坏时抛出 ConfigError。"""
    if not os.path.isfile(path):
        raise ConfigError(
            "未找到%s配置：%s\n"
            "       请先按项目实际情况创建该配置（字段说明见 references/config-guide.md）。"
            % (label, path)
        )
    try:
        with open(path, "r", encoding="utf-8") as handle:
            raw = json.load(handle)
    except (OSError, ValueError) as error:
        raise ConfigError("%s配置读取失败（%s）：%s" % (label, error, path))
    if not isinstance(raw, dict):
        raise ConfigError("%s配置顶层必须是 JSON 对象：%s" % (label, path))
    return raw


def load_config(force_reload=False):
    """加载并合并两层覆盖率配置；缺失或损坏时抛出 ConfigError。

    引擎侧（通用算法参数）与项目侧（项目相关值）分别读取后深度合并，
    项目侧值覆盖引擎侧值。结果进程内缓存，同时写入合并文件供 C# 工具读取。
    """
    global _cached_config
    if _cached_config is not None and not force_reload:
        return _cached_config

    engine = _read_json(ENGINE_CONFIG_PATH, "引擎侧覆盖率")
    project = _read_json(PROJECT_CONFIG_PATH, "项目侧覆盖率")
    merged = _deep_merge(engine, project)

    # 落盘合并结果：C# 工具经 --config 读取该文件，避免工具侧重复实现分层逻辑
    try:
        with open(CONFIG_PATH, "w", encoding="utf-8", newline="\n") as handle:
            json.dump(merged, handle, ensure_ascii=False, indent=2)
    except OSError as error:
        raise ConfigError("合并配置写入失败（%s）：%s" % (error, CONFIG_PATH))

    _cached_config = merged
    return _cached_config


# 区分「未取到值」与「配置值本身就是 None」
_MISSING = object()


def get(path, default=_MISSING):
    """按点分路径读取配置值，如 get("realCoverage.assemblyIncludePrefixes")。

    未传 `default` 时，路径不存在即抛出 ConfigError（配置是唯一事实来源，
    不再静默回退内置默认值）。仅当调用方显式传入 `default` 时才允许缺省。
    """
    node = load_config()
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            if default is _MISSING:
                raise ConfigError(("缺少配置项 `%s`" % path) + (_MISSING_KEY_HINT % CONFIG_PATH))
            return default
        node = node[part]
    if node is None and default is _MISSING:
        raise ConfigError(("配置项 `%s` 为 null" % path) + (_MISSING_KEY_HINT % CONFIG_PATH))
    return node


def get_list(path):
    """读取必需的非空列表配置项；缺失、非列表或为空时抛出 ConfigError。"""
    value = get(path)
    if not isinstance(value, list) or not value:
        raise ConfigError(
            "配置项 `%s` 必须是非空数组，当前为：%r%s" % (path, value, _MISSING_KEY_HINT % CONFIG_PATH)
        )
    return list(value)


