def scan_scope(scope_name):
    """取 --scope 对应的扫描根目录列表。

    `scanScopes.<name>` 缺失时回退到同一配置内的 `scanScopes.all`（仍属配置来源）；
    两者都缺失即报错。
    """
    scopes = get("scanScopes")
    if not isinstance(scopes, dict):
        raise ConfigError("配置项 `scanScopes` 必须是对象" + (_MISSING_KEY_HINT % CONFIG_PATH))
    value = scopes.get(scope_name)
    if isinstance(value, list) and value:
        return list(value)
    fallback = scopes.get("all")
    if isinstance(fallback, list) and fallback:
        return list(fallback)
    raise ConfigError(
        "配置项 `scanScopes.%s` 与 `scanScopes.all` 均缺失或为空%s"
        % (scope_name, _MISSING_KEY_HINT % CONFIG_PATH)
    )


